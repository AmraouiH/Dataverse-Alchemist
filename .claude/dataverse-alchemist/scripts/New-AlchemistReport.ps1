#Requires -Version 7.0
<#
.SYNOPSIS
    Generates the end-of-ticket HTML report (.alchemist/runs/<KEY>/report-<KEY>.html), self-contained (embedded CSS, no
    external resource), in the user's CRM interface language (English or French; other languages fall back to English).

.DESCRIPTION
    -Mode Language : only returns the detected language (call it BEFORE writing report.json, whose texts
                                      must be written in that language).
    -Mode Render   : (default) assembles the report from:
            report.json          written by the agent: summary, steps and statuses, tests, manual actions, docs, PR
            ticket.json          Jira ticket
            context.json         ticket solution and publisher
            journal.jsonl        Dataverse components created / changed
            solution-check.json  presence of the components in the solution (Test-DataverseSolutionComponents.ps1)
    unit-tests/unit-tests.json, ui-tests/ui-tests.json  test results (Invoke-AlchemistUnitTests / UiTests)
    report.json format:
    {
      "summary": "…",
      "branch": "feature/CRM-123-…", "baseBranch": "develop",
      "pullRequest": { "url": "…", "id": "…" },
      "steps": [ { "phase": "…", "title": "…", "status": "done|failed|skipped|manual|warning|pending", "details": "…" } ],
      "tests": [ { "name": "…", "status": "done|failed|skipped|manual", "details": "…" } ],
      "manualActions": [ "…" ],
      "docs": [ { "title": "…", "link": "…" } ]
    }
.EXAMPLE
    New-AlchemistReport.ps1 -IssueKey CRM-123 -Mode Language
    New-AlchemistReport.ps1 -IssueKey CRM-123
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$IssueKey,
    [ValidateSet('Language', 'Render')][string]$Mode = 'Render',
    [int]$Lcid,
    [string]$Environment,
    [string]$ConfigPath
)
$ErrorActionPreference = 'Stop'
Import-Module (Join-Path $PSScriptRoot 'AlchemistCommon.psm1') -Force

$config = Get-AlchemistConfig -ConfigPath $ConfigPath
$IssueKey = $IssueKey.ToUpperInvariant()
$runFolder = Get-AlchemistRunFolder -Config $config -IssueKey $IssueKey
$contextPath = Join-Path $runFolder 'context.json'
$context = if (Test-Path -LiteralPath $contextPath) { Get-Content -Raw -LiteralPath $contextPath | ConvertFrom-Json -AsHashtable } else { @{} }

# Language: -Lcid > language already detected for this ticket > the user's CRM language.
if ($Lcid) { $language = @{ lcid = $Lcid; code = ($Lcid -eq 1036 ? 'fr' : 'en'); source = '-Lcid parameter' } }
elseif ($context.reportLanguage) { $language = $context.reportLanguage }
else {
    $dvEnv = Get-DataverseEnvironment -Config $config -Name $Environment
    $language = Get-DataverseUserLanguage -Config $config -Environment $dvEnv
    $context.reportLanguage = $language
    $context | ConvertTo-Json -Depth 6 | Set-Content -LiteralPath $contextPath -Encoding utf8
}
if ($Mode -eq 'Language') { $language | ConvertTo-Json; return }

$texts = @{
    fr = @{
        title = 'Rapport de réalisation'; generated = 'Généré le'; ticket = 'Ticket'; type = 'Type'; status = 'Statut'
        environment = 'Environnement'; solution = 'Solution'; publisher = 'Éditeur'; branch = 'Branche'; base = 'Branche de départ'
        pr = 'Pull request'; none = 'Aucune'; summary = 'Synthèse'; steps = 'Étapes'; phase = 'Phase'; step = 'Étape'
        details = 'Détails'; components = 'Composants Dataverse'; component = 'Composant'; action = 'Action'; inSolution = 'Dans la solution'
        notChecked = 'non vérifié'; yes = 'Oui'; no = 'Non'; tests = 'Tests'; test = 'Test'; manual = 'Actions manuelles restantes'
        docs = 'Documentation'; footer = 'Généré par Dataverse Alchemist'
        statuses = @{ done = 'Réalisé'; failed = 'En échec'; skipped = 'Non réalisé'; manual = 'Manuel'; warning = 'À vérifier'; pending = 'En attente' }
    }
    en = @{
        title = 'Delivery report'; generated = 'Generated on'; ticket = 'Ticket'; type = 'Type'; status = 'Status'
        environment = 'Environment'; solution = 'Solution'; publisher = 'Publisher'; branch = 'Branch'; base = 'Base branch'
        pr = 'Pull request'; none = 'None'; summary = 'Summary'; steps = 'Steps'; phase = 'Phase'; step = 'Step'
        details = 'Details'; components = 'Dataverse components'; component = 'Component'; action = 'Action'; inSolution = 'In solution'
        notChecked = 'not checked'; yes = 'Yes'; no = 'No'; tests = 'Tests'; test = 'Test'; manual = 'Remaining manual actions'
        docs = 'Documentation'; footer = 'Generated by Dataverse Alchemist'
        statuses = @{ done = 'Done'; failed = 'Failed'; skipped = 'Not done'; manual = 'Manual'; warning = 'To check'; pending = 'Pending' }
    }
}
$t = $texts[$language.code] ?? $texts.en
$culture = try { [Globalization.CultureInfo]::GetCultureInfo([int]$language.lcid) } catch { [Globalization.CultureInfo]::InvariantCulture }

function Read-JsonFile([string]$name) {
    $path = Join-Path $runFolder $name
    if (Test-Path -LiteralPath $path) { return Get-Content -Raw -LiteralPath $path | ConvertFrom-Json -AsHashtable }
    return $null
}
$report = Read-JsonFile 'report.json'
if (-not $report) { throw "report.json not found in $runFolder (to be written by the agent before rendering)." }
$ticket = Read-JsonFile 'ticket.json'
$solutionCheck = Read-JsonFile 'solution-check.json'

# Components from the journal (last action per component).
$components = [ordered]@{}
$journalPath = Join-Path $runFolder 'journal.jsonl'
$pullRequest = $report.pullRequest
if (Test-Path -LiteralPath $journalPath) {
    foreach ($line in Get-Content -LiteralPath $journalPath) {
        if (-not $line.Trim()) { continue }
        $entry = $line | ConvertFrom-Json -AsHashtable
        foreach ($component in @($entry.components)) {
            if ($component -and $component.id) { $components[$component.id.ToLowerInvariant()] = @{ component = $component; action = $entry.action } }
        }
        if ($entry.action -eq 'pullrequest.create' -and -not $pullRequest) { $pullRequest = @{ url = $entry.url; id = $entry.id } }
    }
}
$checked = @{}
if ($solutionCheck) { foreach ($c in @($solutionCheck.components)) { $checked[$c.id.ToLowerInvariant()] = [bool]$c.inSolution } }

function E([object]$value) { [System.Net.WebUtility]::HtmlEncode([string]$value) }
function Badge([string]$status) {
    $s = if ($t.statuses.ContainsKey($status)) { $status } else { 'pending' }
    "<span class=""badge $s"">$(E $t.statuses[$s])</span>"
}
function Link([string]$url, [string]$text) { if ($url) { "<a href=""$(E $url)"">$(E ($text ? $text : $url))</a>" } else { E $t.none } }
function MultiLine([string]$text) { (E $text) -replace "`r?`n", '<br>' }

$steps = @($report.steps)
$counts = $steps | Group-Object { $_.status } | ForEach-Object { "<div class=""kpi""><div class=""kpi-value"">$($_.Count)</div>$(Badge $_.Name)</div>" }
$solution = $context.solution

$html = [Text.StringBuilder]::new()
function Write-Html([string]$text) { [void]$html.AppendLine($text) }

Write-Html "<!DOCTYPE html>"
Write-Html "<html lang=""$(E $language.code)""><head><meta charset=""utf-8""><meta name=""viewport"" content=""width=device-width, initial-scale=1"">"
Write-Html "<title>$(E $IssueKey) · $(E $t.title)</title>"
Write-Html @'
<style>
:root { --fg:#1f2328; --muted:#59636e; --border:#d1d9e0; --bg:#f6f8fa; --accent:#0b5cad;
  --done:#1a7f37; --failed:#cf222e; --skipped:#59636e; --manual:#8250df; --warning:#9a6700; --pending:#0969da; }
* { box-sizing:border-box; }
body { margin:0; font:14px/1.5 "Segoe UI", system-ui, -apple-system, sans-serif; color:var(--fg); background:var(--bg); }
main { max-width:1100px; margin:24px auto; padding:0 16px; }
header, section { background:#fff; border:1px solid var(--border); border-radius:8px; padding:20px 24px; margin-bottom:16px; }
h1 { font-size:22px; margin:0 0 4px; } h2 { font-size:17px; margin:0 0 12px; }
.muted { color:var(--muted); }
.meta { display:grid; grid-template-columns:repeat(auto-fit, minmax(230px, 1fr)); gap:8px 24px; margin-top:16px; }
.meta div span { display:block; font-size:12px; color:var(--muted); text-transform:uppercase; letter-spacing:.03em; }
.kpis { display:flex; flex-wrap:wrap; gap:12px; margin-top:12px; }
.kpi { border:1px solid var(--border); border-radius:8px; padding:8px 16px; text-align:center; min-width:110px; }
.kpi-value { font-size:22px; font-weight:600; }
table { width:100%; border-collapse:collapse; }
th, td { text-align:left; padding:8px 10px; border-bottom:1px solid var(--border); vertical-align:top; }
th { font-size:12px; color:var(--muted); text-transform:uppercase; letter-spacing:.03em; background:var(--bg); }
.badge { display:inline-block; padding:1px 10px; border-radius:999px; font-size:12px; font-weight:600; color:#fff; white-space:nowrap; }
.badge.done { background:var(--done); } .badge.failed { background:var(--failed); } .badge.skipped { background:var(--skipped); }
.badge.manual { background:var(--manual); } .badge.warning { background:var(--warning); } .badge.pending { background:var(--pending); }
code { font-family:Consolas, monospace; font-size:12.5px; background:var(--bg); padding:1px 4px; border-radius:4px; }
a { color:var(--accent); }
footer { text-align:center; color:var(--muted); font-size:12px; margin:24px 0; }
</style></head><body><main>
'@

Write-Html "<header><div class=""muted"">$(E $t.title)</div>"
Write-Html "<h1>$(Link $ticket.url $IssueKey) · $(E $ticket.summary)</h1>"
Write-Html "<div class=""muted"">$(E $t.generated) $(E ((Get-Date).ToString('f', $culture)))</div>"
Write-Html "<div class=""meta"">"
Write-Html "<div><span>$(E $t.type)</span>$(E $ticket.issueType)</div>"
Write-Html "<div><span>$(E $t.environment)</span>$(E ($solution.environment ?? (Get-AlchemistSetting $config 'dataverse.defaultEnvironment')))</div>"
Write-Html "<div><span>$(E $t.solution)</span>$(E $solution.friendlyName) <code>$(E $solution.uniqueName)</code></div>"
Write-Html "<div><span>$(E $t.publisher)</span>$(E $solution.publisher.uniqueName) <code>$(E $solution.publisher.prefix)_</code></div>"
Write-Html "<div><span>$(E $t.base)</span><code>$(E $report.baseBranch)</code></div>"
Write-Html "<div><span>$(E $t.branch)</span><code>$(E $report.branch)</code></div>"
Write-Html "<div><span>$(E $t.pr)</span>$(if ($pullRequest) { Link $pullRequest.url "#$($pullRequest.id)" } else { E $t.none })</div>"
Write-Html "</div></header>"

Write-Html "<section><h2>$(E $t.summary)</h2><p>$(MultiLine $report.summary)</p><div class=""kpis"">$($counts -join '')</div></section>"

Write-Html "<section><h2>$(E $t.steps)</h2><table><thead><tr><th>#</th><th>$(E $t.phase)</th><th>$(E $t.step)</th><th>$(E $t.status)</th><th>$(E $t.details)</th></tr></thead><tbody>"
$i = 0
foreach ($step in $steps) { $i++; Write-Html "<tr><td>$i</td><td>$(E $step.phase)</td><td>$(E $step.title)</td><td>$(Badge $step.status)</td><td>$(MultiLine $step.details)</td></tr>" }
Write-Html "</tbody></table></section>"

if ($components.Count) {
    Write-Html "<section><h2>$(E $t.components)</h2><table><thead><tr><th>$(E $t.type)</th><th>$(E $t.component)</th><th>$(E $t.action)</th><th>$(E $t.inSolution)</th><th>Id</th></tr></thead><tbody>"
    foreach ($item in $components.Values) {
        $c = $item.component
        $key = $c.id.ToLowerInvariant()
        $inSolution = if ($checked.ContainsKey($key)) { if ($checked[$key]) { "<span class=""badge done"">$(E $t.yes)</span>" } else { "<span class=""badge failed"">$(E $t.no)</span>" } } else { "<span class=""muted"">$(E $t.notChecked)</span>" }
        Write-Html "<tr><td>$(E $c.type)</td><td><code>$(E $c.name)</code></td><td>$(E $item.action)</td><td>$inSolution</td><td class=""muted""><code>$(E $c.id)</code></td></tr>"
    }
    Write-Html "</tbody></table></section>"
}

if (@($report.tests).Count) {
    Write-Html "<section><h2>$(E $t.tests)</h2><table><thead><tr><th>$(E $t.test)</th><th>$(E $t.status)</th><th>$(E $t.details)</th></tr></thead><tbody>"
    foreach ($test in @($report.tests)) { Write-Html "<tr><td>$(E $test.name)</td><td>$(Badge $test.status)</td><td>$(MultiLine $test.details)</td></tr>" }
    Write-Html "</tbody></table></section>"
}

# Automatic results: unit tests (unit-tests/unit-tests.json) and browser tests (ui-tests/ui-tests.json).
# Rule: a ticket with a plugin must have its unit tests; otherwise, the Playwright tests. A missing result is flagged.
$fr = $language.code -eq 'fr'
$unit = Read-JsonFile 'unit-tests/unit-tests.json'
$ui = Read-JsonFile 'ui-tests/ui-tests.json'
$hasPlugin = $false
if (Test-Path -LiteralPath $journalPath) { $hasPlugin = [bool](Select-String -LiteralPath $journalPath -Pattern '"dataverse\.plugin(step|assembly)\.' -Quiet) }
function TestBadge([string]$s) { $map = @{ passed = 'done'; failed = 'failed'; flaky = 'warning'; skipped = 'skipped' }; $label = if ($fr) { @{ passed = 'Réussi'; failed = 'En échec'; flaky = 'Instable'; skipped = 'Ignoré' }[$s] } else { @{ passed = 'Passed'; failed = 'Failed'; flaky = 'Flaky'; skipped = 'Skipped' }[$s] }; "<span class=""badge $($map[$s] ?? 'pending')"">$(E $label)</span>" }
function Kpis($r) { "<div class=""kpis""><div class=""kpi""><div class=""kpi-value"">$($r.passed)</div>$(TestBadge 'passed')</div><div class=""kpi""><div class=""kpi-value"">$($r.failed)</div>$(TestBadge 'failed')</div><div class=""kpi""><div class=""kpi-value"">$($r.skipped)</div>$(TestBadge 'skipped')</div></div>" }
$missing = $null
if ($hasPlugin -and -not $unit) { $missing = $fr ? 'Ticket avec plugin : résultats des tests unitaires absents (Invoke-AlchemistUnitTests.ps1 non exécuté).' : 'Ticket with a plugin: unit test results missing (Invoke-AlchemistUnitTests.ps1 not run).' }
elseif (-not $hasPlugin -and -not $ui) { $missing = $fr ? 'Résultats des tests navigateur Playwright absents (Invoke-AlchemistUiTests.ps1 non exécuté).' : 'Playwright browser test results missing (Invoke-AlchemistUiTests.ps1 not run).' }
if ($missing) { Write-Html "<section><h2>$(E ($fr ? 'Résultats de tests' : 'Test results'))</h2><p><span class=""badge failed"">!</span> $(E $missing)</p></section>" }
if ($unit) {
    Write-Html "<section><h2>$(E ($fr ? 'Tests unitaires' : 'Unit tests'))</h2>$(Kpis $unit)<table><thead><tr><th>Suite</th><th>$(E $t.test)</th><th>$(E $t.status)</th><th>ms</th><th>$(E $t.details)</th></tr></thead><tbody>"
    foreach ($s in @($unit.suites)) { foreach ($u in @($s.tests)) { Write-Html "<tr><td>$(E $s.kind) · $(E $s.name)</td><td>$(E $u.name)</td><td>$(TestBadge $u.status)</td><td>$($u.durationMs)</td><td>$(MultiLine $u.error)</td></tr>" } }
    Write-Html "</tbody></table></section>"
}
if ($ui) {
    Write-Html "<section><h2>$(E ($fr ? 'Tests navigateur (Playwright)' : 'Browser tests (Playwright)'))</h2><p class=""muted""><code>$(E $ui.spec)</code> · $(E $ui.environment) · $([math]::Round($ui.durationMs / 1000)) s · <a href=""$(E $ui.htmlReport)"">$(E ($fr ? 'rapport Playwright détaillé (traces)' : 'detailed Playwright report'))</a></p>$(Kpis $ui)"
    Write-Html "<table><thead><tr><th>$(E $t.test)</th><th>$(E $t.status)</th><th>ms</th><th>$(E $t.details)</th></tr></thead><tbody>"
    foreach ($u in @($ui.tests)) {
        $detail = MultiLine (($u.error ?? '') -split "`n" | Select-Object -First 8 | Join-String -Separator "`n")
        # Embedded screenshots (self-contained): all for a failure, the last one for a success
        $shots = @($u.screenshots)
        if ($u.status -ne 'failed') { $shots = @($shots | Select-Object -Last 1) }
        foreach ($rel in $shots) {
            $p = Join-Path $runFolder $rel
            if ($rel -and (Test-Path -LiteralPath $p)) { $detail += "<details><summary>$(E (Split-Path $rel -Leaf))</summary><img style=""max-width:100%;border:1px solid var(--border)"" src=""data:image/png;base64,$([Convert]::ToBase64String([IO.File]::ReadAllBytes($p)))""></details>" }
        }
        Write-Html "<tr><td><span class=""muted"">$(E $u.suite)</span><br>$(E $u.title)</td><td>$(TestBadge $u.status)</td><td>$($u.durationMs)</td><td>$detail</td></tr>"
    }
    Write-Html "</tbody></table></section>"
}

if (@($report.manualActions).Count) {
    Write-Html "<section><h2>$(E $t.manual)</h2><ul>"
    foreach ($action in @($report.manualActions)) { Write-Html "<li>$(MultiLine $action)</li>" }
    Write-Html "</ul></section>"
}

if (@($report.docs).Count) {
    Write-Html "<section><h2>$(E $t.docs)</h2><ul>"
    foreach ($doc in @($report.docs)) { Write-Html "<li>$(Link $doc.link $doc.title)</li>" }
    Write-Html "</ul></section>"
}

$version = Get-Content -Raw -LiteralPath (Join-Path $PSScriptRoot '..\VERSION') -ErrorAction SilentlyContinue
Write-Html "<footer>$(E $t.footer)$(if ($version) { ' v' + $version.Trim() })</footer></main></body></html>"

$out = Join-Path $runFolder "report-$IssueKey.html"
[IO.File]::WriteAllText($out, $html.ToString(), [Text.UTF8Encoding]::new($false))

$statusCounts = [ordered]@{}
$steps | Group-Object { $_.status } | ForEach-Object { $statusCounts[$_.Name] = $_.Count }

[ordered]@{
    report      = $out
    language    = $language.code
    steps       = $steps.Count
    statuses    = $statusCounts
    components  = $components.Count
    pullRequest = $pullRequest.url
} | ConvertTo-Json -Depth 4
